// Generates supabase/migrations/*_seed_curriculum.sql from scripts/curriculum.mjs.
// Usage: npm run db:seed
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { LEVELS, LESSONS, ACHIEVEMENTS } from "./curriculum.mjs";

const OUT = new URL("../supabase/migrations/20261124000004_seed_curriculum.sql", import.meta.url);

const uuid = (key) => {
  const h = createHash("sha1").update("temurlify:" + key).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${((parseInt(h[16], 16) & 3) | 8).toString(16)}${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const shuffle = (arr, r) => {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const k = Math.floor(r() * (i + 1));
    [a[i], a[k]] = [a[k], a[i]];
  }
  return a;
};

function parseWord(raw) {
  const [dePart, uz] = raw.split(";").map((s) => s.trim());
  const m = dePart.match(/^(der|die|das)\s+(.+)$/);
  if (m) {
    const [lemma, plural] = m[2].split(",").map((s) => s.trim());
    return {
      article: m[1],
      de: lemma,
      plural: plural === "pl" ? null : plural || null,
      pos: plural === "pl" ? "noun-plural" : "noun",
      uz,
    };
  }
  const de = dePart;
  let pos = "word";
  if (de.includes(" ")) pos = "phrase";
  else if (/^[a-zäöüß]+$/.test(de) && /(en|ern|eln)$/.test(de)) pos = "verb";
  else if (/^[A-ZÄÖÜ]/.test(de)) pos = "name";
  return { article: null, de, plural: null, pos, uz };
}
const display = (w) => (w.article ? `${w.article} ${w.de}` : w.de);

const out = [];
out.push("-- AUTO-GENERATED by scripts/generate-seed.mjs. Do not edit by hand.");
out.push("-- Curriculum content (120 lessons A1–C1), vocabulary, lesson tests and achievements.\n");

LEVELS.forEach((l, i) =>
  out.push(
    `insert into public.levels (code, title, title_uz, description, position) values (${q(l.code)}, ${q(l.title)}, ${q(l.title_uz)}, ${q(l.description)}, ${i + 1}) on conflict (code) do nothing;`,
  ),
);
out.push("");

let position = 0;
const levelWords = {};
for (const level of Object.keys(LESSONS)) {
  levelWords[level] = LESSONS[level].flatMap((l) => l[3].map(parseWord));
}

let questionCount = 0;
let vocabCount = 0;
const a1Words = [];

for (const level of Object.keys(LESSONS)) {
  for (const [title, titleUz, grammar, words, gq] of LESSONS[level]) {
    position += 1;
    const lessonId = uuid(`lesson:${position}`);
    const parsed = words.map(parseWord);
    if (level === "A1") a1Words.push(...parsed);
    const summary = [
      `## Dars maqsadi`,
      `Bu darsda siz **${titleUz.toLowerCase()}** mavzusidagi asosiy so'z va iboralarni hamda **${grammar}** grammatik mavzusini o'rganasiz.`,
      ``,
      `## Reja`,
      `1. Video darsni to'liq tomosha qiling.`,
      `2. Yangi so'zlarni kartochkalarga qo'shing va takrorlang.`,
      `3. Dars testini topshiring — keyingi dars ochilishi uchun kamida o'tish bali kerak.`,
      ``,
      `## Grammatika`,
      `**${grammar}** — misol: _${gq[0].replace("___", "…")}_`,
    ].join("\n");

    out.push(`-- ${position}. ${title}`);
    out.push(
      `insert into public.lessons (id, level, position, title, title_uz, grammar, summary, duration_min) values (${q(lessonId)}, ${q(level)}, ${position}, ${q(title)}, ${q(titleUz)}, ${q(grammar)}, ${q(summary)}, ${level === "A1" ? 25 : level === "A2" ? 30 : 35}) on conflict (id) do nothing;`,
    );

    const vocabRows = parsed.map((w, i) => {
      vocabCount += 1;
      return `(${q(uuid(`vocab:${position}:${i}`))}, ${q(lessonId)}, ${q(level)}, ${q(w.de)}, ${q(w.article)}, ${q(w.plural)}, ${q(w.pos)}, ${q(w.uz)})`;
    });
    out.push(
      `insert into public.vocabulary (id, lesson_id, level, de, article, plural, part_of_speech, uz) values\n  ${vocabRows.join(",\n  ")}\non conflict (id) do nothing;`,
    );

    // ---- questions --------------------------------------------------------
    const r = rng(position * 7919);
    const questions = [];

    // 1. Grammar question (hand written)
    {
      const [prompt, options, correct, explanation] = gq;
      const order = shuffle(options.map((o, i) => i), r);
      questions.push({
        kind: "single",
        prompt,
        options: order.map((i) => options[i]),
        key: { index: order.indexOf(correct) },
        explanation,
      });
    }

    // 2–5. Meaning questions (German → Uzbek)
    const pool = levelWords[level].filter((w) => !parsed.some((p) => p.uz === w.uz));
    const pick = shuffle(parsed.map((_, i) => i), r).slice(0, 4);
    for (const idx of pick) {
      const w = parsed[idx];
      const distractors = shuffle(pool, r)
        .map((x) => x.uz)
        .filter((u, i, arr) => u !== w.uz && arr.indexOf(u) === i)
        .slice(0, 3);
      const options = shuffle([w.uz, ...distractors], r);
      questions.push({
        kind: "single",
        prompt: `«${display(w)}» so'zining ma'nosi qaysi?`,
        options,
        key: { index: options.indexOf(w.uz) },
        explanation: `${display(w)} — ${w.uz}`,
      });
    }

    // 6. Article question
    const noun = parsed.find((w) => w.pos === "noun" && !pick.includes(parsed.indexOf(w))) || parsed.find((w) => w.pos === "noun");
    if (noun) {
      const options = ["der", "die", "das"];
      questions.push({
        kind: "single",
        prompt: `To'g'ri artiklni tanlang: ___ ${noun.de}`,
        options,
        key: { index: options.indexOf(noun.article) },
        explanation: `${noun.article} ${noun.de}${noun.plural ? ` (ko'plik: ${noun.plural})` : ""} — ${noun.uz}`,
      });
    }

    // 7. Production question (Uzbek → German, typed)
    const typed = parsed.find((w) => w.pos === "verb" && !pick.includes(parsed.indexOf(w))) || parsed.find((w) => w.pos === "verb") || parsed[parsed.length - 1];
    {
      const accepted = [display(typed)];
      if (typed.article) accepted.push(typed.de);
      questions.push({
        kind: "text",
        prompt: `Nemis tilida yozing: «${typed.uz}»`,
        options: [],
        key: { accepted },
        explanation: `To'g'ri javob: ${display(typed)}`,
      });
    }

    const qRows = [];
    const kRows = [];
    questions.forEach((qq, i) => {
      const id = uuid(`question:${position}:${i}`);
      questionCount += 1;
      qRows.push(`(${q(id)}, ${q(lessonId)}, ${q(qq.kind)}, ${q(qq.prompt)}, ${j(qq.options)}, ${q(qq.explanation)}, ${i})`);
      kRows.push(`(${q(id)}, ${j(qq.key)})`);
    });
    out.push(
      `insert into public.questions (id, lesson_id, kind, prompt, options, explanation, position) values\n  ${qRows.join(",\n  ")}\non conflict (id) do nothing;`,
    );
    out.push(`insert into public.question_keys (question_id, answer) values\n  ${kRows.join(",\n  ")}\non conflict (question_id) do nothing;\n`);
  }
}

// Achievements
out.push("-- Achievements");
out.push(
  `insert into public.achievements (code, title, description, icon, metric, threshold, position) values\n  ${ACHIEVEMENTS.map(
    (a, i) => `(${a.map(q).slice(0, 5).join(", ")}, ${a[5]}, ${i + 1})`,
  ).join(",\n  ")}\non conflict (code) do nothing;\n`,
);

// Sample game set (clearly labelled as a template the admin can edit or delete)
const setId = uuid("gameset:a1-sample");
out.push("-- Sample multiplayer game set (template)");
out.push(
  `insert into public.game_sets (id, title, description, level, seconds_per_question) values (${q(setId)}, 'Namuna: A1 so''z boyligi', 'Namuna to''plam — admin paneldan tahrirlash yoki o''chirish mumkin.', 'A1', 20) on conflict (id) do nothing;`,
);
{
  const r = rng(424242);
  const chosen = shuffle(a1Words.filter((w) => w.pos === "noun"), r).slice(0, 12);
  const gq = [];
  const gk = [];
  chosen.forEach((w, i) => {
    const distractors = shuffle(a1Words.filter((x) => x.de !== w.de && x.pos === "noun"), r).slice(0, 3).map(display);
    const options = shuffle([display(w), ...distractors], r);
    const id = uuid(`gameq:a1-sample:${i}`);
    gq.push(`(${q(id)}, ${q(setId)}, ${q(`«${w.uz}» nemis tilida qanday?`)}, ${j(options)}, ${i})`);
    gk.push(`(${q(id)}, ${options.indexOf(display(w))})`);
  });
  out.push(`insert into public.game_questions (id, set_id, prompt, options, position) values\n  ${gq.join(",\n  ")}\non conflict (id) do nothing;`);
  out.push(`insert into public.game_question_keys (question_id, correct_index) values\n  ${gk.join(",\n  ")}\non conflict (question_id) do nothing;`);
}

writeFileSync(OUT, out.join("\n") + "\n");
console.log(`Wrote ${OUT.pathname}: ${position} lessons, ${vocabCount} words, ${questionCount} questions.`);
